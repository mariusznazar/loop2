import { chromium } from 'file:///C:/Users/Mariusz/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error') errors.push(m.text());});
page.on('response',r=>{if(r.status()>=400) errors.push(`${r.status()} ${r.url()}`);});
const root='.runs/task-cycles/wprawa-i-drzewa/reports/';
const results={};
try {
 await page.goto('http://127.0.0.1:8765/.runs/task-cycles/wprawa-i-drzewa/merge-preview.html');
 const ala=page.locator('.team-member').filter({has:page.locator('.team-member-name',{hasText:'Ala'})});
 await ala.getByRole('button',{name:'Kup: Obchód',exact:true}).click();
 await page.getByRole('button',{name:'Dodaj regułę',exact:true}).click();
 const actions=page.getByRole('combobox',{name:'Akcja',exact:true});
 results.hqPatrol=await actions.locator('option[value="patrol"]').count();
 assert.equal(results.hqPatrol,0);
 assert.equal(await page.getByRole('spinbutton',{name:'Zabierz: liczba',exact:true}).inputValue(),'3');
 await page.screenshot({path:root+'merge-ui-hq.png',fullPage:true});
 await ala.getByRole('button',{name:'Wyślij: Ala, mapa Las',exact:true}).click();
 await actions.selectOption('patrol');
 assert.equal(await actions.inputValue(),'patrol');
 await page.getByRole('spinbutton',{name:'Wynieś: liczba',exact:true}).fill('2');
 await page.getByRole('spinbutton',{name:'Wynieś: liczba',exact:true}).press('Tab');
 results.copy=await page.evaluate(()=>({plan:window.preview.get().run.copy.program.tripPlan,snapshot:window.preview.get().run.bringPlan}));
 assert.equal(results.copy.plan.bring[0].count,2);
 assert.equal(results.copy.snapshot[0].count,3);
 await page.getByRole('combobox',{name:'Program:',exact:true}).selectOption('1');
 await actions.selectOption('patrol');
 assert.equal(await page.getByRole('spinbutton',{name:'Wynieś: liczba',exact:true}).inputValue(),'3');
 await page.getByRole('spinbutton',{name:'Wynieś: liczba',exact:true}).fill('4');
 await page.getByRole('spinbutton',{name:'Wynieś: liczba',exact:true}).press('Tab');
 results.saved=await page.evaluate(()=>window.preview.get().programs[0].program.tripPlan);
 assert.equal(results.saved.bring[0].count,4);
 await page.screenshot({path:root+'merge-ui-saved.png',fullPage:true});
 await page.getByRole('combobox',{name:'Program:',exact:true}).selectOption('copy');
 assert.equal(await actions.inputValue(),'patrol');
 assert.equal(await page.getByRole('spinbutton',{name:'Wynieś: liczba',exact:true}).inputValue(),'2');
 await page.screenshot({path:root+'merge-ui-copy.png',fullPage:true});
 await page.evaluate(()=>window.preview.runPractice());
 results.completed=await page.locator('.run-panel').innerText();
 assert.ok(results.completed.includes('Do skrzynki: jagoda 1.'));
 assert.ok(results.completed.includes('Zbieranie małych przedmiotów +5'));
 assert.ok(results.completed.includes('Jedzenie +1'));
 assert.equal(await page.locator('.trip-result:visible').count(),1);
 results.order=await page.locator('.run-panel').evaluate(el=>[...el.children].map(child=>child.className));
 await page.screenshot({path:root+'merge-ui-completed.png',fullPage:true});
 await page.setViewportSize({width:390,height:1100});
 await page.screenshot({path:root+'merge-ui-completed-narrow.png',fullPage:true});
 assert.deepEqual(errors,[]);
 results.errors=errors;
 writeFileSync(root+'merge-ui-results.json',JSON.stringify(results,null,2));
 console.log(JSON.stringify({done:true,screenshots:5,errors}));
} finally {await browser.close();}
