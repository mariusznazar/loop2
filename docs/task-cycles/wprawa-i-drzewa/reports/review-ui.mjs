import { chromium } from 'file:///C:/Users/Mariusz/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';
import { writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const root = '.runs/task-cycles/wprawa-i-drzewa/reports/';
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const result = {};
try {
  await page.goto('http://127.0.0.1:8765/.runs/task-cycles/wprawa-i-drzewa/preview.html');
  await page.getByRole('heading', { name: 'Siedziba', exact: true }).waitFor();
  const ala = page.locator('.team-member').filter({ has: page.locator('.team-member-name', { hasText: 'Ala' }) });
  const ola = page.locator('.team-member').filter({ has: page.locator('.team-member-name', { hasText: 'Ola' }) });
  const branch = ala.getByRole('button', { name: 'Kup: Wprawne oko', exact: true });
  result.before = await branch.locator('..').innerText();
  await branch.focus();
  await branch.press('Enter');
  result.purchase = await branch.evaluate(button => ({ focused: document.activeElement === button, outline: getComputedStyle(button).outlineStyle, text: button.parentElement.innerText }));
  assert.equal(result.purchase.focused, true);
  assert.equal(result.purchase.outline, 'solid');
  assert.equal(await page.evaluate(() => window.preview.get().team.characters[0].skills.smallItemGathering.ranks.keenEye), 1);
  assert.equal(await ola.locator('.skill-branch button:enabled').count(), 0);
  await page.screenshot({ path: root + 'review-ui-headquarters.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await branch.scrollIntoViewIfNeeded();
  result.narrow = await page.evaluate(() => ({ width: innerWidth, content: document.documentElement.scrollWidth }));
  await page.screenshot({ path: root + 'review-ui-narrow.png', fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.evaluate(() => window.preview.runPractice());
  result.completed = await page.locator('.run-practice').innerText();
  assert.equal(result.completed, 'Wprawa w tym przejściu: Zbieranie małych przedmiotów +5 · Jedzenie +1');
  await page.screenshot({ path: root + 'review-ui-completed.png', fullPage: true });
  await page.getByRole('button', { name: 'Restart', exact: true }).click();
  assert.equal(await page.locator('.run-practice').isVisible(), false);
  await page.evaluate(() => window.preview.runPractice(true));
  result.dead = await page.locator('.run-practice').innerText();
  assert.equal(result.dead, 'Wprawa w tym przejściu: Zbieranie małych przedmiotów +5');
  await page.screenshot({ path: root + 'review-ui-dead.png', fullPage: true });
  await page.getByRole('button', { name: 'Zakończ', exact: true }).click();
  assert.equal(await page.locator('.run-practice').isVisible(), false);
  await page.evaluate(() => window.preview.discovery());
  result.discovery = await page.locator('.discovery-text').innerText();
  assert.ok(result.discovery.includes('drzewo umiejętności Eksploracja'));
  await page.screenshot({ path: root + 'review-ui-discovery.png', fullPage: true });
  await page.evaluate(() => window.preview.fresh());
  assert.equal(await page.locator('.character-skills:visible').count(), 0);
  result.errors = errors;
  assert.deepEqual(errors, []);
  writeFileSync(root + 'review-ui-results.json', JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result));
} finally { await browser.close(); }
