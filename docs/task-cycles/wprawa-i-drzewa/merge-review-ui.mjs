import { chromium } from 'file:///C:/Users/Mariusz/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
const browser = await chromium.launch({headless:true, channel:'chrome'});
const page = await browser.newPage({viewport:{width:1440,height:1100}});
const output = '.runs/task-cycles/wprawa-i-drzewa/reports/';
const errors=[];
page.on('pageerror', e=>errors.push(e.message));
page.on('response', r=>{if(r.status()>=400) errors.push(`${r.status()} ${r.url()}`);});
const results={};
try {
  await page.goto('http://127.0.0.1:8765/.runs/task-cycles/wprawa-i-drzewa/merge-preview.html');
  const first = page.locator('.team-member').filter({has:page.locator('.team-member-name',{hasText:'Ala'})});
  await first.getByRole('button',{name:'Kup: Obchód',exact:true}).click();
  await page.getByRole('button',{name:'Dodaj regułę',exact:true}).click();
  const action=page.getByRole('combobox',{name:'Akcja',exact:true});
  assert.equal(await action.locator('option[value="patrol"]').count(),0);
  await page.screenshot({path:output+'merge-review-hq.png',fullPage:true});
  await first.getByRole('button',{name:'Wyślij: Ala, mapa Las',exact:true}).click();
  await action.selectOption('patrol');
  const bring=page.getByRole('spinbutton',{name:'Wynieś: liczba',exact:true});
  await bring.fill('0'); await bring.press('Tab');
  assert.equal(await bring.inputValue(),'0');
  assert.equal(await page.getByText('Wpisz liczbę całkowitą od 1.',{exact:true}).isVisible(),true);
  assert.equal(await page.evaluate(()=>window.preview.get().run.copy.program.tripPlan.bring[0].count),3);
  await page.getByRole('combobox',{name:'Program:',exact:true}).selectOption('1');
  assert.equal(await bring.inputValue(),'3');
  await action.selectOption('patrol');
  await bring.fill('5'); await bring.press('Tab');
  await page.getByRole('combobox',{name:'Program:',exact:true}).selectOption('copy');
  assert.equal(await bring.inputValue(),'3');
  await bring.fill('2'); await bring.press('Tab');
  results.plans=await page.evaluate(()=>({copy:window.preview.get().run.copy.program.tripPlan.bring,saved:window.preview.get().programs[0].program.tripPlan.bring,frozen:window.preview.get().run.bringPlan}));
  assert.equal(results.plans.copy[0].count,2);
  assert.equal(results.plans.saved[0].count,5);
  assert.equal(results.plans.frozen[0].count,3);
  await page.screenshot({path:output+'merge-review-running.png',fullPage:true});
  await page.evaluate(()=>window.preview.runPractice());
  const deposited=page.getByText('Do skrzynki: jagoda 1.',{exact:true});
  assert.equal(await deposited.isVisible(),true);
  assert.equal(await page.locator('.run-practice').innerText(),'Wprawa w tym przejściu: Zbieranie małych przedmiotów +5 · Jedzenie +1');
  const boxes=await page.locator('.run-panel').evaluate(element=>[...element.children].filter(child=>!child.hidden).map(child=>({className:child.className,text:child.textContent,y:child.getBoundingClientRect().top})));
  results.completed=boxes;
  assert.ok(boxes.find(item=>item.text==='Do skrzynki: jagoda 1.').y < boxes.find(item=>item.className==='run-practice').y);
  assert.equal(await page.locator('.trip-result:visible').count(),1);
  await page.screenshot({path:output+'merge-review-completed.png',fullPage:true});
  await page.setViewportSize({width:390,height:1100});
  await page.screenshot({path:output+'merge-review-narrow.png',fullPage:true});
  await page.evaluate(()=>window.preview.runPractice(true));
  assert.equal(await page.locator('.run-practice').innerText(),'Wprawa w tym przejściu: Zbieranie małych przedmiotów +5');
  assert.equal(await page.locator('.trip-result:visible').count(),0);
  await page.screenshot({path:output+'merge-review-death.png',fullPage:true});
  await page.getByRole('button',{name:'Restart',exact:true}).click();
  assert.equal(await page.locator('.run-practice').isVisible(),false);
  assert.equal(await page.locator('.trip-result:visible').innerText(),'Wyniesie: jagoda 3');
  assert.deepEqual(errors,[]);
  results.errors=errors;
  writeFileSync(output+'merge-review-ui.json',JSON.stringify(results,null,2));
  console.log('PASS UI: purchase, both editors, invalid draft, frozen plan, completion, death, restart; 5 screenshots');
} finally { await browser.close(); }
