import { chromium } from 'file:///C:/Users/Mariusz/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';
import { writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
page.on('console',message=>{if(message.type()==='error') errors.push(message.text());});
page.on('response',response=>{if(response.status()>=400) errors.push(`${response.status()} ${response.url()}`);});
const result={};
const root='.runs/task-cycles/wprawa-i-drzewa/reports/';
try {
 await page.goto('http://127.0.0.1:8765/.runs/task-cycles/wprawa-i-drzewa/preview.html');
 await page.getByRole('heading',{name:'Siedziba'}).waitFor();
 result.initial=await page.locator('.team-member').evaluateAll(rows=>rows.map(row=>({name:row.querySelector('.team-member-name').textContent,skills:[...row.querySelectorAll('.skill-summary')].map(x=>x.textContent),enabled:[...row.querySelectorAll('.skill-branch button')].filter(x=>!x.disabled).length})));
 const ala=page.locator('.team-member').filter({has:page.locator('.team-member-name',{hasText:'Ala'})});
 const purchase=ala.getByRole('button',{name:'Kup: Wprawny krok',exact:true});
 await purchase.focus();await purchase.press('Enter');
 result.purchase=await purchase.evaluate(button=>({focused:document.activeElement===button,outline:getComputedStyle(button).outlineStyle,row:button.parentElement.textContent}));
 await page.screenshot({path:root+'ui-hq.png',fullPage:true});
 await ala.getByRole('button',{name:'Kup: Obchód',exact:true}).click();
 result.max=await ala.getByRole('button',{name:'Kup: Obchód',exact:true}).evaluate(button=>({disabled:button.disabled,text:button.parentElement.textContent}));
 for(let i=0;i<3;i++) await ala.getByRole('button',{name:'Kup: Szybki posiłek',exact:true}).click();
 result.numericMax=await ala.getByRole('button',{name:'Kup: Szybki posiłek',exact:true}).evaluate(button=>({disabled:button.disabled,text:button.parentElement.textContent}));
 await page.getByRole('button',{name:'Dodaj regułę',exact:true}).click();
 const actions=page.getByRole('combobox',{name:'Akcja',exact:true});
 result.hqActions=await actions.locator('option').evaluateAll(nodes=>nodes.map(x=>x.value));
 assert.equal(result.hqActions.includes('patrol'),false);
 await ala.getByRole('button',{name:'Wyślij: Ala, mapa Las',exact:true}).click();
 result.ownerCopyActions=await actions.locator('option').evaluateAll(nodes=>nodes.map(x=>x.value));
 assert.ok(result.ownerCopyActions.includes('patrol'));
 await actions.selectOption('patrol');
 await page.getByRole('combobox',{name:'Program:',exact:true}).selectOption('1');
 result.ownerSavedActions=await actions.locator('option').evaluateAll(nodes=>nodes.map(x=>x.value));
 assert.ok(result.ownerSavedActions.includes('patrol'));
 await actions.selectOption('patrol');
 await page.getByRole('combobox',{name:'Program:',exact:true}).selectOption('copy');
 result.runSelects=await page.locator('select').evaluateAll(nodes=>nodes.map(x=>({label:x.getAttribute('aria-label'),options:[...x.options].map(o=>({value:o.value,text:o.textContent}))})));
 await page.screenshot({path:root+'ui-owner-run.png',fullPage:true});
 await page.getByRole('button',{name:'Zakończ',exact:true}).click();
 const ola=page.locator('.team-member').filter({has:page.locator('.team-member-name',{hasText:'Ola'})});
 await ola.getByRole('button',{name:'Wyślij: Ola, mapa Las',exact:true}).click();
 result.nonowner=await page.evaluate(()=>({practice:window.preview.get().run.practice,action:window.preview.get().run.current.activity,held:window.preview.get().run.copy.program.groups[0].rules[0].action}));
 result.nonownerOptions=await actions.locator('option').evaluateAll(nodes=>nodes.map(x=>({value:x.value,disabled:x.disabled})));
 assert.deepEqual(result.nonowner.held,{kind:'patrol',resource:'stick'});
 assert.equal(result.nonowner.action.kind,'wait');
 await page.screenshot({path:root+'ui-nonowner-run.png',fullPage:true});
 await page.evaluate(()=>window.preview.runPractice());
 result.completed=await page.locator('.run-practice').innerText();
 await page.screenshot({path:root+'ui-completed.png',fullPage:true});
 await page.evaluate(()=>window.preview.runPractice(true));
 result.dead=await page.locator('.run-practice').innerText();
 await page.screenshot({path:root+'ui-dead.png',fullPage:true});
 await page.evaluate(()=>window.preview.discovery());
 result.discovery=await page.locator('.discovery-text').innerText();
 assert.ok(result.discovery.includes('drzewo umiejętności Eksploracja'));
 await page.screenshot({path:root+'ui-discovery.png',fullPage:true});
 await page.evaluate(()=>window.preview.fresh());
 result.freshSections=await page.locator('.character-skills:visible').count();
 assert.equal(result.freshSections,0);
 assert.equal(result.purchase.focused,true);
 assert.equal(result.purchase.outline,'solid');
 assert.equal(result.max.disabled,true);
 assert.equal(result.numericMax.disabled,true);
 assert.equal(result.numericMax.text.includes('cena'),false);
 assert.equal(result.numericMax.text.includes('po kupnie'),false);
 assert.equal(result.initial[1].enabled,0);
 assert.equal(result.dead,'Wprawa w tym przejściu: Zbieranie małych przedmiotów +5');
 await page.screenshot({path:root+'ui-fresh.png',fullPage:true});
 result.errors=errors;
 assert.deepEqual(errors,[]);
 writeFileSync(root+'ui-results.json',JSON.stringify(result,null,2));
 console.log(JSON.stringify({completed:true,errors,count:Object.keys(result).length}));
} finally {await browser.close();}
