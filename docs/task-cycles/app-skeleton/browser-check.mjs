import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(pathToFileURL(process.env.LOOP_PLAYWRIGHT_MODULE));
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage();
  const consoleErrors = [];
  const pageErrors = [];
  const failedRequests = [];
  page.on('console', message => { if (message.type() === 'error') consoleErrors.push(message.text()); });
  page.on('pageerror', error => pageErrors.push(error.message));
  page.on('requestfailed', request => failedRequests.push({ url: request.url(), failure: request.failure() }));
  const moduleResponse = page.waitForResponse(response => new URL(response.url()).pathname === '/main.js');
  const response = await page.goto('http://127.0.0.1:3000/', { waitUntil: 'networkidle' });
  const module = await moduleResponse;
  const result = await page.evaluate(() => ({ title: document.title, text: document.body.innerText, mainCount: document.querySelectorAll('main').length, mainChildren: document.querySelector('main')?.childElementCount, mainText: document.querySelector('main')?.textContent, script: document.querySelector('script[type="module"]')?.getAttribute('src') }));
  await page.screenshot({ path: '.runs/task-cycles/app-skeleton/browser.png', fullPage: true });
  const evidence = { browser: await browser.version(), status: response.status(), moduleStatus: module.status(), ...result, consoleErrors, pageErrors, failedRequests };
  await writeFile('.runs/task-cycles/app-skeleton/browser.json', JSON.stringify(evidence, null, 2));
  console.log(JSON.stringify(evidence));
  assert.equal(evidence.status, 200);
  assert.equal(evidence.moduleStatus, 200);
  assert.equal(result.mainCount, 1);
  assert.equal(result.mainChildren, 0);
  assert.equal(result.mainText, '');
  assert.equal(result.text, '');
  assert.deepEqual(consoleErrors, []);
  assert.deepEqual(pageErrors, []);
  assert.deepEqual(failedRequests, []);
} finally { await browser.close(); }
